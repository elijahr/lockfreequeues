## Render benchmark results into the README's <!-- BENCHMARKS:start --> /
## <!-- BENCHMARKS:end --> block.
##
## Reads `benchmarks/results/latest.json` and updates `README.md` in place.
## If the JSON is missing or malformed, writes a placeholder table so the
## README still has shape; numbers can be regenerated later by re-running:
##
##   nim r benchmarks/render_readme.nim
##
## Idempotent: running it twice produces the same output.
##
## PR 0 (bench-rollup, Task 0.13) switched the input from the legacy
## `bench_main` aggregator JSON (`{results: [{...}], metadata: {...}}`)
## to native Bencher Metric Format JSON
## (`{slug: {measure: {value, lower_value?, upper_value?}}}`) emitted by
## `bench_throughput --bmf-out` (Task 0.10) and merged via merge_bmf.py
## (Task 0.7). The slug shape is `<library>/<topology>/<P>p<C>c`; this
## file walks the slug to recover the (impl, thread_config) pair the
## table renders.

import std/[json, os, strformat, strutils, algorithm, times]
import std/[cpuinfo]

const
  StartMarker = "<!-- BENCHMARKS:start -->"
  EndMarker = "<!-- BENCHMARKS:end -->"

type Row = object
  impl: string
  threads: string
  throughput: float
  latencyP50: float
  hasLatency: bool

proc placeholderTable(): string =
  result =
    "| implementation | threads | throughput (ops/ms) | p50 latency (ns) |\n" &
    "|----------------|---------|---------------------|------------------|\n" &
    "| _no benchmark results checked in_ | — | — | — |\n\n" &
    "_Numbers regenerated by `nim r benchmarks/render_readme.nim` from " &
    "`benchmarks/results/latest.json`._\n"

proc fmtFloat(x: float, digits: int = 1): string =
  if x == 0.0:
    return "—"
  result = formatFloat(x, ffDecimal, digits)
  # `ffDecimal` with 0 digits leaves a trailing "."; strip it for tidiness.
  if digits == 0 and result.endsWith('.'):
    result.setLen(result.len - 1)

proc detectMetadata(): tuple[platform: string, cores: int, timestamp: string] =
  ## BMF (per-slug measures keyed by name) does not carry a metadata block,
  ## so render_readme reconstructs the platform / cores / timestamp line
  ## from the renderer's own runtime instead of pulling from JSON. Devs
  ## who want to override (e.g. when re-rendering historical snapshots
  ## from a different host) can set the BENCH_RENDER_PLATFORM /
  ## BENCH_RENDER_CORES / BENCH_RENDER_TIMESTAMP env vars.
  let envPlat = getEnv("BENCH_RENDER_PLATFORM")
  let platform =
    if envPlat.len > 0: envPlat
    else: hostOS & "/" & hostCPU
  let envCores = getEnv("BENCH_RENDER_CORES")
  var cores = 0
  if envCores.len > 0:
    try: cores = parseInt(envCores)
    except CatchableError: cores = 0
  if cores <= 0:
    cores = countProcessors()
  let envTs = getEnv("BENCH_RENDER_TIMESTAMP")
  let timestamp =
    if envTs.len > 0: envTs
    else: now().utc.format("yyyy-MM-dd HH:mm:ss") & " UTC"
  result = (platform, cores, timestamp)

proc renderTable(rows: seq[Row], meta: JsonNode): string =
  var lines: seq[string]
  # `meta` is reserved for callers that DO carry a metadata block (older
  # JSON shapes, future BMF-with-metadata extensions). When meta is nil
  # — the BMF default — fall back to runtime detection so the README
  # still surfaces a "Platform / cores / timestamp" line for context.
  let detected = detectMetadata()
  let platform =
    if meta != nil: meta{"platform"}.getStr(detected.platform)
    else: detected.platform
  let cores =
    if meta != nil: meta{"cores"}.getInt(detected.cores)
    else: detected.cores
  let timestamp =
    if meta != nil: meta{"timestamp"}.getStr(detected.timestamp)
    else: detected.timestamp
  var metaLine = "_Platform: " & platform
  if cores > 0:
    metaLine &= ", " & $cores & " cores"
  if timestamp.len > 0:
    metaLine &= ", " & timestamp
  metaLine &= "._"
  lines.add metaLine
  lines.add ""
  lines.add "| implementation | threads | throughput (ops/ms) | p50 latency (ns) |"
  lines.add "|----------------|---------|---------------------|------------------|"
  for r in rows:
    let lat =
      if r.hasLatency and r.latencyP50 > 0.0:
        fmtFloat(r.latencyP50, 0)
      else:
        "—"
    lines.add &"| `{r.impl}` | {r.threads} | {fmtFloat(r.throughput)} | {lat} |"
  lines.add ""
  lines.add "_Numbers regenerated by `nim r benchmarks/render_readme.nim` " &
    "from `benchmarks/results/latest.json`._"
  result = lines.join("\n") & "\n"

proc parseSlug(slug: string): tuple[impl, threads: string, ok: bool] =
  ## Split `<library>/<topology>/<P>p<C>c` into (library, "<P>P/<C>C").
  ## Returns ok=false if the slug shape does not match.
  ##
  ## Example: "lockfreequeues_sipsic/spsc/1p1c" -> ("lockfreequeues_sipsic", "1P/1C", true)
  let parts = slug.split('/')
  if parts.len != 3:
    return ("", "", false)
  let shape = parts[2]
  let pIdx = shape.find('p')
  let cIdx = shape.find('c')
  if pIdx <= 0 or cIdx <= pIdx + 1 or cIdx != shape.high:
    return ("", "", false)
  let producers = shape[0 ..< pIdx]
  let consumers = shape[pIdx + 1 ..< cIdx]
  # Validate digits — keep this strict so `mpsc_unbounded`-suffixed
  # slugs (which have a non-digit `_unbounded` segment) still slot in,
  # because the topology lives in parts[1] and `<P>p<C>c` lives in
  # parts[2] regardless of the topology name.
  for ch in producers:
    if ch notin {'0'..'9'}: return ("", "", false)
  for ch in consumers:
    if ch notin {'0'..'9'}: return ("", "", false)
  result = (parts[0], producers & "P/" & consumers & "C", true)

proc loadRows(path: string): tuple[rows: seq[Row], meta: JsonNode] =
  ## Parse a BMF JSON file (`{slug: {measure: {value, ...}}}`).
  ##
  ## Slug walk: each top-level key is `<lib>/<topology>/<P>p<C>c`. The
  ## library becomes `Row.impl`; (P, C) pair becomes `Row.threads`. The
  ## `throughput_ops_ms.value` measure becomes `Row.throughput`. Latency
  ## measures (`latency_p50_ns` etc.) populate `Row.latencyP50` /
  ## `Row.hasLatency` when present (PR 1+ emits these; PR 0 does not).
  ##
  ## BMF has no `metadata` block, so the second tuple slot is always
  ## `nil` for the new shape. Callers must accept `meta == nil`.
  let raw = readFile(path)
  let doc = parseJson(raw)
  var rows: seq[Row]
  if doc.kind != JObject:
    return (rows, nil)
  for slug, slugNode in doc.pairs:
    if slugNode.kind != JObject:
      continue
    let parsed = parseSlug(slug)
    if not parsed.ok:
      continue
    var row = Row(impl: parsed.impl, threads: parsed.threads)
    let throughput = slugNode{"throughput_ops_ms"}{"value"}
    if throughput != nil:
      row.throughput = throughput.getFloat(0.0)
    let p50 = slugNode{"latency_p50_ns"}{"value"}
    if p50 != nil:
      row.latencyP50 = p50.getFloat(0.0)
      row.hasLatency = row.latencyP50 > 0.0
    rows.add row
  # Stable sort: by impl then by thread_config so the table has a
  # predictable order regardless of JSON hash-table iteration order.
  rows.sort(
    proc(a, b: Row): int =
      result = cmp(a.impl, b.impl)
      if result == 0:
        result = cmp(a.threads, b.threads)
  )
  # Cap rows to keep the README compact, but high enough that the cap is
  # only an emergency brake — the variant set today is ~11 (1 sipsic, 4
  # mupmuc shapes, 3 unbounded mupsic, 3 channels) and grows in PR 3 / PR
  # 4 with comparison adapters. PR 5 replaces this auto-rendered block
  # with a hand-curated 4-row summary plus a link to the live docs chart,
  # so this cap is a transitional safeguard, not the long-term shape.
  if rows.len > 32:
    rows.setLen(32)
  return (rows, nil)

proc renderBlock(jsonPath: string): string =
  if not fileExists(jsonPath):
    echo "render_readme: ", jsonPath, " missing; writing placeholder table."
    return placeholderTable()
  try:
    let (rows, meta) = loadRows(jsonPath)
    if rows.len == 0:
      echo "render_readme: no rows in ", jsonPath, "; writing placeholder."
      return placeholderTable()
    return renderTable(rows, meta)
  except CatchableError as e:
    echo "render_readme: failed to parse ",
      jsonPath, ": ", e.msg, "; writing placeholder."
    return placeholderTable()

proc updateReadme(readmePath, body: string) =
  let original = readFile(readmePath)
  let startIdx = original.find(StartMarker)
  let endIdx = original.find(EndMarker)
  if startIdx < 0 or endIdx < 0 or endIdx < startIdx:
    quit("render_readme: BENCHMARKS markers not found in " & readmePath, 1)
  let prefix = original[0 .. startIdx + StartMarker.len - 1]
  let suffix = original[endIdx .. original.high]
  let newContent = prefix & "\n" & body & "\n" & suffix
  if newContent == original:
    echo "render_readme: README unchanged."
    return
  writeFile(readmePath, newContent)
  echo "render_readme: updated ", readmePath, "."

# Guard the CLI entry point with `renderReadmeNoMain` so unit tests
# (`tests/t_render_readme.nim`) can `include` this file to access the
# private helpers (loadRows, renderTable, parseSlug, ...) without
# triggering the README rewrite. `nim r` and CLI invocations leave the
# define unset and so still run main as before.
when isMainModule and not defined(renderReadmeNoMain):
  let here = currentSourcePath().parentDir()
  let projectRoot = here.parentDir()
  let jsonPath = projectRoot / "benchmarks" / "results" / "latest.json"
  let readmePath = projectRoot / "README.md"
  let body = renderBlock(jsonPath)
  updateReadme(readmePath, body)
  echo "render_readme: done."
