## Render the benchmark table block in README.md from
## benchmarks/results/latest.json.
##
## The README contains a region delimited by:
##
##     <!-- BENCHMARKS:start -->
##     ...table goes here...
##     <!-- BENCHMARKS:end -->
##
## This script reads the JSON, picks a representative subset of rows
## (one per implementation/thread_config), and rewrites the block.
##
## Run via `nimble benchmarks:readme`.

import std/algorithm
import std/json
import std/os
import std/strformat
import std/strutils

const
  StartMarker = "<!-- BENCHMARKS:start -->"
  EndMarker = "<!-- BENCHMARKS:end -->"
  MaxRows = 8

type Row = object
  impl: string
  threadConfig: string
  thrMean: float
  p50: float
  p99: float

proc loadRows(path: string): seq[Row] =
  let data = parseFile(path)
  for r in data["results"].items:
    let metrics = r["metrics"]
    let thr = metrics["throughput_ops_ms"]
    let lat = metrics["latency_ns"]
    result.add Row(
      impl: r["implementation"].getStr,
      threadConfig: r["thread_config"].getStr,
      thrMean: thr["mean"].getFloat,
      p50: lat["p50"].getFloat,
      p99: lat["p99"].getFloat,
    )

proc threadOrder(s: string): int =
  ## "1P/1C" -> 1, "2P/2C" -> 2, etc. Used to sort rows naturally.
  if s.len == 0:
    return 0
  let firstDigit = s.split('P')[0]
  try:
    result = parseInt(firstDigit)
  except ValueError:
    result = 0

proc selectRepresentative(rows: seq[Row]): seq[Row] =
  ## Pick at most MaxRows rows. Preference: lockfreequeues entries first,
  ## then everything else, sorted by thread count within each impl.
  var sorted = rows
  sorted.sort(
    proc(a, b: Row): int =
      let aLfq = a.impl.startsWith("lockfreequeues")
      let bLfq = b.impl.startsWith("lockfreequeues")
      if aLfq != bLfq:
        return (if aLfq: -1 else: 1)
      if a.impl != b.impl:
        return cmp(a.impl, b.impl)
      return cmp(threadOrder(a.threadConfig), threadOrder(b.threadConfig))
  )
  result = sorted[0 ..< min(sorted.len, MaxRows)]

proc fmtInt(x: float): string =
  ## Format a float as a base-10 integer string with thousands separators.
  let n = int(x + 0.5)
  let raw = $n
  for i, c in raw:
    if i > 0 and (raw.len - i) mod 3 == 0:
      result.add ','
    result.add c

proc renderTable(rows: seq[Row]): string =
  result.add "| Implementation | Threads | Throughput (ops/ms) | p50 latency (ns) | p99 latency (ns) |\n"
  result.add "|---|---|---:|---:|---:|\n"
  for r in rows:
    let p50 =
      if r.p50 == 0.0:
        "n/a"
      else:
        fmtInt(r.p50)
    let p99 =
      if r.p99 == 0.0:
        "n/a"
      else:
        fmtInt(r.p99)
    let thr = fmtInt(r.thrMean)
    result.add fmt("| `{r.impl}` | {r.threadConfig} | {thr} | {p50} | {p99} |") & "\n"

proc renderBlock(rows: seq[Row], metaTimestamp, metaPlatform: string): string =
  result.add "Numbers regenerated by `nimble benchmarks:readme` from `benchmarks/results/latest.json`. "
  result.add "See [`benchmarks/`](benchmarks/) for the full suite.\n\n"
  result.add fmt"_Last run: {metaTimestamp} on {metaPlatform}._" & "\n\n"
  result.add renderTable(rows)

proc rewriteReadme(readmePath, newBody: string) =
  let original = readFile(readmePath)
  let startIdx = original.find(StartMarker)
  let endIdx = original.find(EndMarker)
  if startIdx < 0 or endIdx < 0 or endIdx < startIdx:
    quit("Could not find BENCHMARKS markers in " & readmePath, 1)
  let before = original[0 .. startIdx + StartMarker.len - 1]
  let after = original[endIdx ..< original.len]
  let updated = before & "\n\n" & newBody & "\n" & after
  if updated == original:
    echo "README benchmark block unchanged."
    return
  writeFile(readmePath, updated)
  echo "Updated benchmark block in ", readmePath

when isMainModule:
  let
    here = currentSourcePath().parentDir
    repoRoot = here.parentDir
    jsonPath = repoRoot / "benchmarks" / "results" / "latest.json"
    readmePath = repoRoot / "README.md"

  if not fileExists(jsonPath):
    quit("Missing " & jsonPath, 1)
  if not fileExists(readmePath):
    quit("Missing " & readmePath, 1)

  let raw = parseFile(jsonPath)
  let meta = raw["metadata"]
  let rows = loadRows(jsonPath).selectRepresentative
  let body = renderBlock(rows, meta["timestamp"].getStr, meta["platform"].getStr)
  rewriteReadme(readmePath, body)
